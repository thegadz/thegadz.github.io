param(
  [string]$CatalogPath = "",
  [string]$OutPath = ""
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
if (-not $CatalogPath) { $CatalogPath = Join-Path $root "db\catalog.json" }
if (-not $OutPath) { $OutPath = Join-Path $root "db\seed.sql" }

function Sql([string]$value) {
  return "'" + ($value -replace "'", "''") + "'"
}

$json = [System.IO.File]::ReadAllText($CatalogPath, [System.Text.Encoding]::UTF8) | ConvertFrom-Json
$categories = @($json.categories)
$products = @($json.products)

if ($categories.Count -ne 5) { throw "Expected 5 categories, found $($categories.Count)" }
if ($products.Count -ne 73) { throw "Expected 73 products, found $($products.Count)" }

$categoryOrder = @{}
for ($i = 0; $i -lt $categories.Count; $i++) {
  $categoryOrder[$categories[$i].slug] = $i + 1
}

$slugs = @{}
$productSort = @{}
$lines = New-Object System.Collections.Generic.List[string]

$lines.Add("-- thegadzstore catalog seed. Generated by db\build-seed.ps1 from db\catalog.json.")
$lines.Add("-- Resets the catalog in place. Orders are intentionally untouched.")
$lines.Add("DELETE FROM denominations;")
$lines.Add("DELETE FROM products;")
$lines.Add("")

$categoryValues = @()
foreach ($category in $categories) {
  $categoryValues += "(" + (Sql $category.slug) + ", " + (Sql $category.name) + ", " + [int]$category.sort + ", 1)"
}
$lines.Add("INSERT INTO categories (slug, name, sort, active) VALUES")
$lines.Add(($categoryValues -join ",`n"))
$lines.Add("ON CONFLICT(slug) DO UPDATE SET name=excluded.name, sort=excluded.sort, active=excluded.active;")
$lines.Add("")

$productValues = @()
foreach ($product in $products) {
  $slug = [string]$product.slug
  if ($slugs.ContainsKey($slug)) { throw "Duplicate product slug: $slug" }
  $slugs[$slug] = $true
  if (-not $categoryOrder.ContainsKey([string]$product.category)) { throw "Unknown category for $slug" }
  if ($product.denominations.Count -lt 3 -or $product.denominations.Count -gt 5) {
    throw "$slug has $($product.denominations.Count) denominations; expected 3-5"
  }
  if ([string]$product.color -notmatch '^#[0-9a-fA-F]{6}$') { throw "$slug has invalid color $($product.color)" }

  if (-not $productSort.ContainsKey([string]$product.category)) { $productSort[[string]$product.category] = 0 }
  $productSort[[string]$product.category] = [int]$productSort[[string]$product.category] + 1
  $sort = $productSort[[string]$product.category]

  $target = [string]$product.target_type
  $name = [string]$product.name
  if ($target -eq "phone") {
    $description = "Isi $name instan, aman, dan murah. Masukkan nomor HP aktif dengan benar."
  } elseif ($target -eq "account") {
    $description = "Beli $name instan, aman, dan murah. Masukkan User ID atau email tujuan dengan benar."
  } elseif ([int]$product.requires_zone -eq 1) {
    $description = "Top up $name instan, aman, dan murah. Masukkan Player ID dan Zone ID dengan benar."
  } else {
    $description = "Top up $name instan, aman, dan murah. Masukkan Player ID dengan benar."
  }
  $short = [string]$product.unit
  if ([int]$product.requires_zone -eq 1) { $short += " " + [char]0x00B7 + " butuh Zone ID" }

  $values = "(" + (Sql $slug) + ", " + (Sql $name) + ", (SELECT id FROM categories WHERE slug=" + (Sql ([string]$product.category)) + "), " +
    (Sql ([string]$product.unit)) + ", " + (Sql $short) + ", " + (Sql ([string]$product.icon)) + ", " + (Sql ([string]$product.color)) + ", " +
    (Sql ([string]([string]$product.image).Trim())) + ", " +
    (Sql $target) + ", " + [int]$product.requires_zone + ", " + (Sql $description) + ", 1, $sort)"
  $productValues += $values
}

$lines.Add("INSERT INTO products (slug, name, category_id, unit, short, icon, color, image, target_type, requires_zone, description, active, sort) VALUES")
$lines.Add(($productValues -join ",`n") + ";")
$lines.Add("")

foreach ($category in $categories) {
  $rows = @()
  foreach ($product in $products) {
    if ([string]$product.category -ne [string]$category.slug) { continue }
    $index = 0
    foreach ($denomination in $product.denominations) {
      $index++
      if ([int]$denomination.price -le 0) { throw "$($product.slug) denomination $index has invalid price" }
      $rows += "(" + (Sql ([string]$product.slug)) + ", " + (Sql $denomination.label) + ", " + [int]$denomination.price + ", $index)"
    }
  }
  if (-not $rows.Count) { continue }
  $lines.Add("WITH data(product_slug, label, price, sort) AS (VALUES")
  $lines.Add(($rows -join ",`n"))
  $lines.Add(")")
  $lines.Add("INSERT INTO denominations (product_id, label, price, compare_at, sku, supplier_code, active, sort)")
  $lines.Add("SELECT p.id, data.label, data.price, 0, upper(replace(data.product_slug, '-', '')) || '-' || data.sort, '', 1, data.sort")
  $lines.Add("FROM data JOIN products p ON p.slug = data.product_slug;")
  $lines.Add("")
}

$lines.Add("-- End of generated seed.")

$encoding = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($OutPath, ($lines -join "`n"), $encoding)

$denominationCount = ($products | ForEach-Object { $_.denominations.Count } | Measure-Object -Sum).Sum
Write-Host "Wrote $OutPath"
Write-Host "  categories: $($categories.Count)"
Write-Host "  products:   $($products.Count)"
Write-Host "  denominations: $denominationCount"
